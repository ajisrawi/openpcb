/**
 * More manufacturing / analysis outputs:
 *   ipc356        IPC-D-356A netlist for bare-board electrical test (fixed 80-column records, metric units)
 *   vrml          VRML 2.0 model of the board (outline extruded to board thickness) and component bodies
 *   impedance     trace impedance (IPC-2141 closed forms): microstrip, stripline, and their edge-coupled pairs
 */
import { type Project, padToBoard, padAngle, viaLayers } from './model.js';
import { defaultLibrary } from './footprints.js';
import { padInstances } from './connectivity.js';

/* ---------------- IPC-D-356A ---------------- */

const fixed = (v: number, n: number) => String(Math.min(10 ** n - 1, Math.max(0, Math.round(Math.abs(v))))).padStart(n, '0');
const signed = (v: number, n: number) => (v < 0 ? '-' : '+') + fixed(v, n);

export function exportIpc356(p: Project): string {
  const lib = { ...defaultLibrary(), ...p.footprints };
  const out = ['C  IPC-D-356A netlist generated by OpenBoard', `C  Board: ${p.name}`, `P  JOB   ${p.name.slice(0, 60)}`, 'P  UNITS CUST 1', 'P  DIM   N'];
  // net names longer than 14 characters go through NNAME aliases
  const alias = new Map<string, string>(); let na = 1;
  const netField = (net: string): string => {
    if (!net) return 'N/C';
    if (net.length <= 14) return net;
    let a = alias.get(net); if (!a) { a = `NNAME${na++}`; alias.set(net, a); out.push(`P  ${a.padEnd(6)}  ${net}`); }
    return a;
  };
  const um = (mm: number) => mm * 1000;   // CUST 1: 0.001 mm units
  const last = p.layers[p.layers.length - 1].name, first = p.layers[0].name;
  const records: string[] = [];
  for (const pd of padInstances(p)) {
    const c = p.components.find((x) => x.ref === pd.ref)!;
    const pad = lib[c.footprint]?.pads.find((x) => x.id === pd.padId);
    const th = !!pd.th;
    const access = th ? '00' : pd.layers.includes(first) ? '01' : pd.layers.includes(last) ? '02' : '00';
    const drill = th ? `D${fixed(um(pad?.drill ?? Math.min(pd.w, pd.h) / 2), 4)}P` : '      ';
    const rot = ((Math.round(padAngle(c, pad ?? {})) % 360) + 360) % 360;
    const mask = th ? '3' : access === '01' ? '1' : '2';
    records.push(`${th ? '317' : '327'}${netField(pd.net).padEnd(14).slice(0, 14)}   ${pd.ref.padEnd(6).slice(0, 6)}-${pd.padId.padEnd(4).slice(0, 4)} ${drill}A${access}X${signed(um(pd.center.x), 6)}Y${signed(um(pd.center.y), 6)}X${fixed(um(pd.w), 4)}Y${fixed(um(pd.h), 4)}R${fixed(rot, 3)} S${mask}`);
  }
  for (const v of p.vias) {
    const ls = viaLayers(p, v);
    const access = ls.length === p.layers.length ? '00' : ls[0] === first ? '01' : ls[ls.length - 1] === last ? '02' : '00';
    records.push(`317${netField(v.net).padEnd(14).slice(0, 14)}   VIA   -    M D${fixed(um(v.drill), 4)}PA${access}X${signed(um(v.x), 6)}Y${signed(um(v.y), 6)}X${fixed(um(v.diameter), 4)}Y${fixed(um(v.diameter), 4)}R000 S0`);
  }
  void padToBoard;
  return [...out, ...records, '999', ''].join('\n');
}

/* ---------------- VRML 2.0 ---------------- */

export function exportVrml(p: Project, opts: { thickness?: number } = {}): string {
  const lib = { ...defaultLibrary(), ...p.footprints };
  const t = opts.thickness ?? 1.6;
  const pts = p.outline;
  const out = ['#VRML V2.0 utf8', `# ${p.name} — board and component bodies (mm), generated by OpenBoard`];
  // board: outline extruded (top face, bottom face as a fan from the first vertex, side walls)
  const coords: string[] = [];
  for (const q of pts) coords.push(`${q.x.toFixed(4)} ${q.y.toFixed(4)} 0`);
  for (const q of pts) coords.push(`${q.x.toFixed(4)} ${q.y.toFixed(4)} ${(-t).toFixed(4)}`);
  const n = pts.length, faces: string[] = [];
  faces.push([...Array(n).keys()].join(' ') + ' -1');
  faces.push([...Array(n).keys()].reverse().map((i) => i + n).join(' ') + ' -1');
  for (let i = 0; i < n; i++) { const j = (i + 1) % n; faces.push(`${i} ${i + n} ${j + n} ${j} -1`); }
  out.push(`Shape { appearance Appearance { material Material { diffuseColor 0.1 0.4 0.15 } } geometry IndexedFaceSet { solid FALSE coord Coordinate { point [ ${coords.join(', ')} ] } coordIndex [ ${faces.join(' ')} ] } }`);
  // component bodies: boxes sized from the footprint body, height from the package family
  const height = (fp: string) => /^(C|R)_0(2|4)/i.test(fp.replace(/^.*:/, '')) ? 0.5 : /BGA|QFN|DFN/i.test(fp) ? 1.0 : /SOIC|SOT|QFP|TSSOP/i.test(fp) ? 1.6 : /Header|Conn|RJ45|USB|DC/i.test(fp) ? 8.5 : /Hole|TestPoint/i.test(fp) ? 0 : 1.2;
  for (const c of p.components) {
    const fp = lib[c.footprint]; if (!fp) continue;
    const hgt = height(c.footprint); if (hgt <= 0) continue;
    const z = c.side === 'front' ? hgt / 2 : -t - hgt / 2;
    const col = /^U/.test(c.ref) ? '0.15 0.15 0.15' : /^(R|C|L)\d/.test(c.ref) ? '0.55 0.45 0.3' : '0.6 0.6 0.65';
    out.push(`Transform { translation ${c.x.toFixed(4)} ${c.y.toFixed(4)} ${z.toFixed(4)} rotation 0 0 1 ${((c.rot * Math.PI) / 180).toFixed(5)} children Shape { appearance Appearance { material Material { diffuseColor ${col} } } geometry Box { size ${fp.body.w.toFixed(3)} ${fp.body.h.toFixed(3)} ${hgt.toFixed(3)} } } }`);
  }
  return out.join('\n') + '\n';
}

/* ---------------- impedance (IPC-2141) ---------------- */

export interface ImpedanceInput { type: 'microstrip' | 'stripline'; w: number; h: number; t?: number; er: number; s?: number; b?: number }

/** Characteristic impedance (ohm) of a trace, and the differential impedance when a pair gap `s` is given.
 *  Microstrip: h = dielectric height to the reference plane. Stripline: b = plane-to-plane spacing (default 2h + t). */
export function impedance(i: ImpedanceInput): { z0: number; zdiff?: number } {
  const t = i.t ?? 0.035;
  let z0: number;
  if (i.type === 'microstrip') z0 = (87 / Math.sqrt(i.er + 1.41)) * Math.log((5.98 * i.h) / (0.8 * i.w + t));
  else { const b = i.b ?? 2 * i.h + t; z0 = (60 / Math.sqrt(i.er)) * Math.log((4 * b) / (0.67 * Math.PI * (0.8 * i.w + t))); }
  if (i.s === undefined) return { z0 };
  // edge-coupled pair (IPC-2141 approximations)
  const zdiff = i.type === 'microstrip' ? 2 * z0 * (1 - 0.48 * Math.exp((-0.96 * i.s) / i.h)) : 2 * z0 * (1 - 0.347 * Math.exp((-2.9 * i.s) / (i.b ?? 2 * i.h + t)));
  return { z0, zdiff };
}
