/** Polylines (mm) for `text` centred at `at`, `height` mm tall; `mirror` flips it for bottom-side silkscreen. */
export function strokeText(text: string, at: Pt, height: number, mirror = false): Pt[][] {
  const s = height / 6;
  const chars = [...text.toUpperCase()];
  const width = (chars.length * 5 - 1) * s;
  const out: Pt[][] = [];
  chars.forEach((ch, i) => {
    const glyph = G[ch] ?? G['#'];
    for (const pl of glyph) {
      const pts: Pt[] = [];
      for (let k = 0; k + 1 < pl.length; k += 2) {
        let x = (i * 5 + pl[k]) * s - width / 2;
        const y = pl[k + 1] * s - height / 2;
        if (mirror) x = -x;
        pts.push({ x: at.x + x, y: at.y + y });
      }
      if (pts.length) out.push(pts);
    }
  });
  return out;
}
